import express from 'express';
import cors from 'cors';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import 'dotenv/config';
import authRoutes from './routes/auth.js';
import projectsRoutes from './routes/projects.js';
import certificatesRoutes from './routes/certificates.js';
import profileRoutes from './routes/profile.js';
import { initializeDatabase, closeDatabase } from './db/database.js';
const __dirname=path.dirname(fileURLToPath(import.meta.url));
const app=express();const PORT=process.env.PORT||5000;
if(!process.env.JWT_SECRET||process.env.JWT_SECRET.length<32) throw new Error('JWT_SECRET must be set to a random secret of at least 32 characters.');
app.use(cors({origin:process.env.CORS_ORIGIN?process.env.CORS_ORIGIN.split(',').map(s=>s.trim()):true}));
app.use(express.json({limit:'1mb'}));
app.use('/uploads',express.static(process.env.UPLOADS_DIR||path.join(__dirname,'uploads')));
app.get('/api/health',async(_req,res)=>res.json({status:'ok',database:'postgresql'}));
app.use('/api/auth',authRoutes);app.use('/api/projects',projectsRoutes);app.use('/api/certificates',certificatesRoutes);app.use('/api/profile',profileRoutes);
app.use((err,_req,res,_next)=>{console.error(err);res.status(500).json({message:'Server error.'});});
await initializeDatabase();
const server=app.listen(PORT,()=>console.log(`Portfolio API running on port ${PORT}`));
async function shutdown(){server.close(async()=>{await closeDatabase();process.exit(0);});}
process.on('SIGTERM',shutdown);process.on('SIGINT',shutdown);
